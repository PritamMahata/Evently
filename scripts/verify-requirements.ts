import "dotenv/config";
import fs from "fs";
import { closePool } from "@/lib/db/pool";
import { makeCtx, REQUIREMENTS, type Status } from "./requirements";

async function main() {
  const ctx = makeCtx();
  const rows: {
    r: (typeof REQUIREMENTS)[number];
    status: Status;
    why: string;
  }[] = [];
  for (const r of REQUIREMENTS) {
    if (r.manual) {
      rows.push({ r, status: "MANUAL", why: r.manual });
      continue;
    }
    const fail = await r.check!(ctx);
    rows.push({ r, status: fail ? "FAIL" : "PASS", why: fail ?? "" });
  }

  console.log(
    "========================================\nEVENTLY REQUIREMENT VERIFICATION\n========================================",
  );
  let group = "";
  for (const { r, status, why } of rows) {
    if (r.group !== group) {
      group = r.group;
      console.log(`\n${group}`);
    }
    const mark = status === "PASS" ? "✓" : status === "MANUAL" ? "⚠" : "✗ FAIL";
    console.log(`${mark} ${r.id}  ${r.title}${why ? `\n    → ${why}` : ""}`);
  }
  const core = rows.filter((x) => !x.r.bonus && x.status !== "MANUAL");
  const corePass = core.filter((x) => x.status === "PASS").length;
  const bonus = rows.filter((x) => x.r.bonus);
  const failures = rows.filter((x) => x.status === "FAIL");
  console.log(
    `\n========================================\nRESULT\n========================================`,
  );
  console.log(`CORE (automatable): ${corePass}/${core.length} PASS`);
  console.log(
    `BONUS: ${bonus.filter((b) => b.status === "PASS").length}/${bonus.length} PASS`,
  );
  console.log(
    `MANUAL: ${rows
      .filter((x) => x.status === "MANUAL")
      .map((x) => x.r.id)
      .join(", ")}`,
  );
  console.log(
    `\nFINAL STATUS: ${failures.length ? "NOT READY — fix the FAIL items above" : "READY FOR MANUAL REVIEW"}\n========================================`,
  );

  if (process.argv.includes("--write-matrix")) {
    const esc = (s: string) => s.replace(/\|/g, "\\|");
    const lines = [
      "# Requirement compliance matrix",
      "",
      "> Generated by `npm run verify:requirements -- --write-matrix`. Statuses come from real evidence (unit tests, HTTP e2e run, live schema inspection) — never hand-edited.",
      `> Last generated: ${new Date().toISOString()}`,
      "",
      "| ID | Requirement | Implementation | Test / verification | Status |",
      "|----|-------------|----------------|---------------------|--------|",
      ...rows.map(
        ({ r, status }) =>
          `| ${r.id} | ${esc(r.title)} | ${esc(r.impl)} | ${esc(r.test)} | ${status === "MANUAL" ? "MANUAL" : status} |`,
      ),
      "",
      "## Manual items",
      "",
      ...rows
        .filter((x) => x.status === "MANUAL")
        .map((x) => `- **${x.r.id}** — ${x.why}`),
      "",
    ];
    fs.writeFileSync("docs/REQUIREMENTS.md", lines.join("\n"));
    console.log("docs/REQUIREMENTS.md written");
  }
  process.exitCode = failures.length ? 1 : 0;
}
main()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(closePool);
